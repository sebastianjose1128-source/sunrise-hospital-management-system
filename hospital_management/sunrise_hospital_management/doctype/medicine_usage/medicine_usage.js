frappe.ui.form.on("Medicine Usage", {

    // -----------------------------------------
    // FORM LOAD
    // -----------------------------------------

    setup(frm) {

        // Show only active stock medicines
        // that have batch tracking enabled.

        frm.set_query("item_code", function () {
            return {
                filters: {
                    disabled: 0,
                    is_stock_item: 1,
                    has_batch_no: 1
                }
            };
        });


        // Show only actual warehouses.
        // Exclude warehouse groups.

        frm.set_query("warehouse", function () {
            return {
                filters: {
                    is_group: 0
                }
            };
        });


        // Show batches belonging to selected medicine.

        frm.set_query("batch_no", function () {
            return {
                filters: {
                    item: frm.doc.item_code || "",
                    disabled: 0
                }
            };
        });

    },


    // -----------------------------------------
    // PATIENT ADMISSION SELECTION
    // -----------------------------------------

    patient_admission(frm) {

        // Clear previously fetched values.

        frm.set_value("patient", "");
        frm.set_value("doctor", "");

        if (!frm.doc.patient_admission) {
            return;
        }

        let admission = frm.doc.patient_admission;

        // Fetch Patient and Doctor from Admission.

        frappe.db.get_value(
            "Patient Admission",
            admission,
            ["patient", "doctor"]
        ).then(r => {

            // Prevent an outdated response from
            // overwriting a newly selected admission.

            if (frm.doc.patient_admission !== admission) {
                return;
            }

            if (r.message) {

                frm.set_value(
                    "patient",
                    r.message.patient
                );

                frm.set_value(
                    "doctor",
                    r.message.doctor
                );

            }

        });

    },


    // -----------------------------------------
    // MEDICINE SELECTION
    // -----------------------------------------

    item_code(frm) {

        // Previous batch may belong to another medicine.

        frm.set_value("batch_no", "");

        // Reset previous calculated values.

        frm.set_value("rate", 0);
        frm.set_value("total_medicine_charges", 0);

    },


    // -----------------------------------------
    // WAREHOUSE SELECTION
    // -----------------------------------------

    warehouse(frm) {

        // Clear previously selected batch.

        frm.set_value("batch_no", "");

        frm.set_value("rate", 0);
        frm.set_value("total_medicine_charges", 0);

    },


    // -----------------------------------------
    // FORM REFRESH
    // -----------------------------------------

    refresh(frm) {

        // Display Stock Entry only after submission
        // and when a Stock Entry is linked.

        frm.toggle_display(
            "stock_entry",
            frm.doc.docstatus === 1 && !!frm.doc.stock_entry
        );

    },


    // -----------------------------------------
    // AFTER SUBMISSION
    // -----------------------------------------

    on_submit(frm) {

        // Reload the document to fetch the
        // Stock Entry generated by Python.

        frm.reload_doc();

    }

});